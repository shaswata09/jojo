// Writes src/i18n/resources.ts: one static import per catalog file.
//
// Metro cannot glob, so the phone's catalogs are listed by hand — and a list
// kept by hand is the kind that forgets a file. This writes it instead, and
// `src/i18n/catalogs.test.ts` fails when the list and the folder disagree.
//
//   node scripts/i18n-index.mjs
import { readdirSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../src/i18n/locales/', import.meta.url))
const locales = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()
const ident = (locale, ns) => `${locale}_${ns}`.replace(/[^A-Za-z0-9_]/g, '_')
const imports = []
const entries = []
for (const locale of locales) {
  const namespaces = readdirSync(root + locale)
    .filter((f) => f.endsWith('.json'))
    .map((f) => f.slice(0, -5))
    .sort()
  imports.push(
    ...namespaces.map((ns) => `import ${ident(locale, ns)} from './locales/${locale}/${ns}.json'`),
  )
  entries.push(
    `  '${locale}': { ${namespaces.map((ns) => `${JSON.stringify(ns)}: ${ident(locale, ns)}`).join(', ')} },`,
  )
}
writeFileSync(
  fileURLToPath(new URL('../src/i18n/resources.ts', import.meta.url)),
  `// Generated by scripts/i18n-index.mjs — run it after adding a catalog file.\n${imports.join('\n')}\n\nexport const RESOURCES = {\n${entries.join('\n')}\n} as const\n`,
)
console.log(`${locales.length} languages`)
